#!/usr/bin/env python3
"""Build the paste-a-link editions from the installed skills.

Usage:
  python3 tools/build_link_editions.py           # write link/
  python3 tools/build_link_editions.py --check   # check generated pages

Run tools/build_all.py to sync shared text first. This builder gives Markdown
pages full addresses for their links and combines the main instructions with
the task procedure for two common econ-learn requests.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_skill_zips as bz  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
OUT = ROOT / "link"
RAW_BASE = "https://raw.githubusercontent.com/ningzhanglab/Econ-Agent-Skills/main"
GENERATED = "<!-- Generated by tools/build_link_editions.py"
INDEX_NAME = "econ-skills"
TERM_TASK = "term-or-screenshot"
HOMEWORK_TASK = "homework-exam"
LEARN_TASKS = (TERM_TASK, HOMEWORK_TASK)
RENAMED = {"econ-teaching": "econ-learn", "econ-writing": "econ-write"}

# Relative Markdown links. Leave web links and anchors on the current page alone.
LOCAL_LINK_RE = re.compile(r"\]\((?![a-z][a-z0-9+.-]*:|#)([^)#\s]+)(?:#([^)\s]*))?(\s+[\"'][^\n]*?[\"'])?\)")

NOTE = """> **Edition code: `{code}`**
>
> You are reading this skill from a link. Open the task pages and guides required for the request. If a required page cannot be opened, name it and pause the part that depends on it.
>
> When first using this skill, start the reply with `Skill edition: {code}`. When using the combined index, follow its format for skill names and multiple codes. End the reply with one line naming the skill files you actually read.
"""

INDEX_NOTE = """Use this table to open the pages needed for the current request. For terms or homework, open the combined page. If it is unavailable, open the main `econ-learn` page and the task page linked beside it instead.

Use multiple skills in task order. To explain a paper and place it in the literature, use `econ-learn` and then `econ-research`. For a referee report, assess the paper with `econ-learn`, position it with `econ-research`, then structure the report with `econ-write`.

All four skills are available through this index. Reuse instructions already read in this chat and open additional pages as needed. If a required page cannot be opened, name it and pause the part that depends on it.

When first using a skill, start the reply with one `Skill edition:` line listing each newly used skill and its page's code. End with one line naming the skill files actually read.
"""

REDIRECT = """<!-- Generated by tools/build_link_editions.py. Do not edit. -->

# {old} is now {new}

> **This skill was renamed.** `{old}` is now `{new}`, with its files in a new layout. This page holds no rules.
>
> Open {base}/link/{new}.md and follow that page. If it cannot be opened, say so and stop; do not answer from memory. If the request is for slides or a talk, open {base}/link/econ-present.md instead.
"""


def edition_code(skill_dir: Path) -> str:
    """Six hex characters covering the installed skill and the link generator."""
    digest = hashlib.sha256()
    digest.update(Path(__file__).read_bytes())
    digest.update(b"\0")
    for path in bz.included_files(skill_dir):
        digest.update(path.relative_to(skill_dir).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()[:6]


def link_path(skill: str, rel: Path) -> Path:
    if rel == Path("SKILL.md"):
        return Path(f"{skill}.md")
    return Path(skill) / rel


def link_url(path: Path) -> str:
    return f"{RAW_BASE}/link/{path.as_posix()}"


def absolute_links(text: str, source: Path, skill_dir: Path, included: Path | None = None) -> str:
    root = skill_dir.resolve()

    def absolute(match: re.Match) -> str:
        rel, anchor, title = match.groups()
        target = (source.parent / rel).resolve()
        if not target.is_relative_to(root) or not target.is_file():
            raise ValueError(f"{source} links to a missing or external file: {rel}")
        destination = target.relative_to(root)
        if target == included:
            url = f"#{anchor or 'included-task-procedure'}"
        elif destination.suffix == ".md":
            url = link_url(link_path(skill_dir.name, destination))
        else:
            url = f"{RAW_BASE}/skills/{skill_dir.name}/{destination.as_posix()}"
        link = f"]({url}{title or ''})"
        if anchor and target != included:
            return f'{link} (section "{anchor}")'
        return link

    return LOCAL_LINK_RE.sub(absolute, text).strip("\n")


def generated_header(skill_dir: Path, *sources: Path) -> str:
    names = ", ".join(f"skills/{skill_dir.name}/{source.as_posix()}" for source in sources)
    return f"{GENERATED} from {names}. Do not edit. -->"


def render_reference(skill_dir: Path, source: Path) -> str:
    path = skill_dir / source
    body = absolute_links(path.read_text(encoding="utf-8"), path, skill_dir)
    return f"{generated_header(skill_dir, source)}\n\n{body}\n"


def render(skill_dir: Path, task: str | None = None) -> str:
    main_name = Path("SKILL.md")
    main = skill_dir / main_name
    text = main.read_text(encoding="utf-8")
    parts = text.split("---\n", 2)
    if not text.startswith("---\n") or len(parts) < 3:
        raise ValueError(f"{main} has no YAML frontmatter")
    note = NOTE.format(code=edition_code(skill_dir))
    if task is None:
        body = absolute_links(parts[2], main, skill_dir)
        return "\n".join([generated_header(skill_dir, main_name), "", note, body, ""])

    task_name = Path("tasks") / f"{task}.md"
    task_path = skill_dir / task_name
    body = absolute_links(parts[2], main, skill_dir, task_path.resolve())
    procedure = absolute_links(task_path.read_text(encoding="utf-8"), task_path, skill_dir)
    return "\n".join([
        generated_header(skill_dir, main_name, task_name),
        "",
        note.rstrip(),
        ">",
        f"> This page includes `SKILL.md` and `{task_name.as_posix()}`. Read the procedure below and open any additional pages the request needs.",
        "",
        body,
        "",
        "## Included task procedure",
        "",
        procedure,
        "",
    ])


def render_index() -> str:
    learn_routes = [
        ("Explain a standalone term or a screenshot from a book, paper or website", TERM_TASK),
        ("Solve homework or a past exam, or prepare for an exam", HOMEWORK_TASK),
    ]
    other_routes = [
        ("Understand a lecture, model, derivation or paper, or organize course material",
         "econ-learn", Path("econ-learn.md")),
        ("Build or revise slides for an audience", "econ-present", Path("econ-present.md")),
        ("Edit, review or structure the user's own writing", "econ-write", Path("econ-write.md")),
        ("Develop a research question, find or verify references, or synthesize the literature",
         "econ-research", Path("econ-research.md")),
    ]
    rows = []
    for request, task in learn_routes:
        bundle = Path("econ-learn") / f"{task}.md"
        procedure = bundle.parent / "tasks" / bundle.name
        rows.append(f"| {request} | [econ-learn with task]({link_url(bundle)})"
                    f" · [Task page]({link_url(procedure)}) |")
    rows.extend(f"| {request} | [{label}]({link_url(path)}) |" for request, label, path in other_routes)
    return "\n".join([
        f"{GENERATED}. Do not edit. -->",
        "",
        "# Econ Agent Skills",
        "",
        INDEX_NOTE,
        "| The user wants to… | Open |",
        "| --- | --- |",
        *rows,
        "",
    ])


def generated_pages() -> dict[Path, str]:
    pages = {}
    for name in bz.skill_names(SKILLS):
        skill_dir = SKILLS / name
        pages[OUT / f"{name}.md"] = render(skill_dir)
        for path in bz.included_files(skill_dir):
            rel = path.relative_to(skill_dir)
            if rel.suffix == ".md" and rel != Path("SKILL.md"):
                pages[OUT / link_path(name, rel)] = render_reference(skill_dir, rel)
    for task in LEARN_TASKS:
        pages[OUT / "econ-learn" / f"{task}.md"] = render(SKILLS / "econ-learn", task)
    pages[OUT / f"{INDEX_NAME}.md"] = render_index()
    pages.update({
        OUT / f"{old}.md": REDIRECT.format(old=old, new=new, base=RAW_BASE)
        for old, new in RENAMED.items()
    })
    return pages


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="do not write; fail if link/ is out of date")
    args = parser.parse_args(argv)

    stale = False
    pages = generated_pages()
    for target, wanted in pages.items():
        relative = target.relative_to(ROOT)
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == wanted:
            print(f"OK: {relative} is up to date")
        elif args.check:
            stale = True
            print(f"ERROR: {relative} is out of date; run python3 tools/build_link_editions.py")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(wanted, encoding="utf-8")
            print(f"WROTE: {relative}")
    for target in sorted(set(OUT.rglob("*.md")) - pages.keys()):
        if target.read_text(encoding="utf-8").startswith(GENERATED):
            relative = target.relative_to(ROOT)
            if args.check:
                stale = True
                print(f"ERROR: {relative} is no longer generated; run python3 tools/build_link_editions.py")
            else:
                target.unlink()
                print(f"REMOVED: {relative}")
    return int(stale)


if __name__ == "__main__":
    sys.exit(main())
