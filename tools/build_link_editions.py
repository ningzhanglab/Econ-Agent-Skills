#!/usr/bin/env python3
"""Build the paste-a-link editions from the installed skills.

Usage:
  python3 tools/build_link_editions.py           # write link/ and the README router
  python3 tools/build_link_editions.py --check   # check generated pages

Run tools/build_all.py to sync shared text first. A user who pastes links
reads one page per request, so each kind of request in ROUTES gets one
self-contained page in link/route/: the skill's SKILL.md followed by every
task page, guide and template that request needs. The same table builds the
index and the router block in README.md that users paste into a chat Project.
Per-skill and per-file pages stay as fallbacks, with full addresses.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_skill_zips as bz  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
OUT = ROOT / "link"
RAW_BASE = "https://raw.githubusercontent.com/ningzhanglab/Econ-Agent-Skills/main"
GENERATED = "<!-- Generated by tools/build_link_editions.py"
INDEX_NAME = "econ-skills"
RENAMED = {"econ-teaching": "econ-learn", "econ-writing": "econ-write"}
README = ROOT / "README.md"
ROUTER_BLOCK = re.compile(r"(<!-- link-router -->\n).*?(<!-- /link-router -->)", re.S)
# A route page must fit one comfortable fetch.
ROUTE_BUDGET = 50_000

# One row per kind of request: (page name, what the user wants, skill, files the request needs).
ROUTES = (
    ("term", "A term, concept, or screenshot of equations",
     "econ-learn", ("tasks/term-or-screenshot.md",)),
    ("homework", "Homework, a past exam, or exam prep",
     "econ-learn", ("tasks/homework-exam.md", "guides/macroeconomics.md", "guides/microeconomics.md",
                    "guides/econometrics.md", "guides/time-series.md", "tasks/deliver-file.md",
                    "templates/simple-notes.tex", "templates/simple-notes-cn.tex")),
    ("explain", "Why something holds, a mechanism, a derivation or proof",
     "econ-learn", ("tasks/explain.md", "tasks/derive.md")),
    ("paper", "A research paper or part of one",
     "econ-learn", ("tasks/paper.md",)),
    ("lecture", "A whole lecture, notes, linking lectures, or another file",
     "econ-learn", ("tasks/whole-lecture.md", "tasks/cross-lecture.md", "tasks/deliver-file.md",
                    "guides/figures.md", "guides/reading-sources.md",
                    "templates/simple-notes.tex", "templates/simple-notes-cn.tex")),
    ("course", "Organizing a course, or a study log",
     "econ-learn", ("tasks/course.md", "tasks/learning-log.md", "guides/sources-and-versions.md",
                    "guides/large-files.md")),
    ("slides", "Slides for an audience",
     "econ-present", ("tasks/deliver-file.md", "tasks/revise-deck.md", "tasks/content-file.md",
                      "templates/simple-slides.tex", "templates/simple-handout.tex")),
    ("writing", "Editing or reviewing my own writing",
     "econ-write", ("guides/terminology-and-notation.md", "guides/econ-conventions.md", "guides/ai-tells.md",
                    "templates/simple-report.tex")),
    ("research", "A research question, the literature, or checking references",
     "econ-research", ("tasks/research-questions.md", "tasks/literature-search.md",
                       "tasks/literature-synthesis.md")),
)
# Combined pages from before the routes existed; they now point to their route.
MOVED = {"econ-learn/term-or-screenshot.md": "term", "econ-learn/homework-exam.md": "homework"}

# Relative Markdown links. Leave web links and anchors on the current page alone.
LOCAL_LINK_RE = re.compile(r"\]\((?![a-z][a-z0-9+.-]*:|#)([^)#\s]+)(?:#([^)\s]*))?(\s+[\"'][^\n]*?[\"'])?\)")

NOTE = """> **Edition code: `{code}`**
>
> You are reading this skill from a link. Open the task pages and guides required for the request. If a required page cannot be opened, name it and pause the part that depends on it.
>
> Start every reply that follows this page with the line `Skill: {name} · {code}`.
"""

ROUTE_NOTE = """> **Edition code: `{code}`**
>
> You are reading this skill from a link. This page holds `SKILL.md` and {listed}: everything this kind of request needs. Links to those files point to their section below. Open another page only when the request needs something this page names only as a link; if it cannot be opened, name it and pause the part that depends on it.
>
> Start every reply that follows this page with the line `Skill: {name} · {code}`. This page covers one kind of request: when a later message in the chat asks for another kind, open that kind's page before answering.
"""

INDEX_NOTE = """Open the one page in this table that matches the request and follow it: each page holds the skill's rules together with every procedure and guide that kind of request needs. If the request has several parts, open each page and work in task order (a referee report: paper, then research, then writing).

If a page cannot be opened, open the skill's main page instead ({fallbacks}) and the pages it links; name any page that still cannot be opened and pause the part that depends on it.

Pick the page again for every message, including later messages in the same chat: open it if it has not been opened in this chat, or reuse it if it has. Start each reply that follows a page with the `Skill:` line that page gives.
"""

ROUTER = """Econ Agent Skills. For every message, later ones included, open the page below that fits it (unless already opened in this chat) and follow it. Start each such reply with the page's `Skill:` line. If a page fails to open, say so. Write all math in LaTeX, even single symbols.

{rows}

A message with several kinds of request: use each page, in order."""

MOVED_PAGE = """<!-- Generated by tools/build_link_editions.py. Do not edit. -->

# This page moved

> This combined page is now `{url}`. Open that page and follow it. If it cannot be opened, say so and open `{base}/link/econ-learn.md`.
"""

REDIRECT = """<!-- Generated by tools/build_link_editions.py. Do not edit. -->

# {old} is now {new}

> **This skill was renamed.** `{old}` is now `{new}`, with its files in a new layout. This page holds no rules.
>
> Open {base}/link/{new}.md and follow that page. If it cannot be opened, say so and stop; do not answer from memory. If the request is for slides or a talk, open {base}/link/econ-present.md instead.
"""


def edition_code(skill_dir: Path) -> str:
    """Six hex characters covering the installed skill and the link generator."""
    digest = hashlib.sha256()
    digest.update(Path(__file__).read_bytes())
    digest.update(b"\0")
    for path in bz.included_files(skill_dir):
        digest.update(path.relative_to(skill_dir).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()[:6]


def link_path(skill: str, rel: Path) -> Path:
    if rel == Path("SKILL.md"):
        return Path(f"{skill}.md")
    return Path(skill) / rel


def link_url(path: Path) -> str:
    return f"{RAW_BASE}/link/{path.as_posix()}"


def absolute_links(text: str, source: Path, skill_dir: Path, included: dict[Path, str] | None = None) -> str:
    """Give every relative link a full address; a link to a file included on this page becomes an anchor."""
    root = skill_dir.resolve()
    included = included or {}

    def absolute(match: re.Match) -> str:
        rel, anchor, title = match.groups()
        target = (source.parent / rel).resolve()
        if not target.is_relative_to(root) or not target.is_file():
            raise ValueError(f"{source} links to a missing or external file: {rel}")
        destination = target.relative_to(root)
        if target in included:
            return f"](#{anchor or included[target]}{title or ''})"
        if destination.suffix == ".md":
            url = link_url(link_path(skill_dir.name, destination))
        else:
            url = f"{RAW_BASE}/skills/{skill_dir.name}/{destination.as_posix()}"
        link = f"]({url}{title or ''})"
        return f'{link} (section "{anchor}")' if anchor else link

    return LOCAL_LINK_RE.sub(absolute, text).strip("\n")


def generated_header(skill_dir: Path, *sources: Path) -> str:
    names = ", ".join(f"skills/{skill_dir.name}/{source.as_posix()}" for source in sources)
    return f"{GENERATED} from {names}. Do not edit. -->"


def render_reference(skill_dir: Path, source: Path) -> str:
    path = skill_dir / source
    body = absolute_links(path.read_text(encoding="utf-8"), path, skill_dir)
    return f"{generated_header(skill_dir, source)}\n\n{body}\n"


def skill_body(skill_dir: Path) -> str:
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    parts = text.split("---\n", 2)
    if not text.startswith("---\n") or len(parts) < 3:
        raise ValueError(f"{skill_dir / 'SKILL.md'} has no YAML frontmatter")
    return parts[2]


def render(skill_dir: Path) -> str:
    """The skill's main page: SKILL.md with full addresses, for the fallback route."""
    main = skill_dir / "SKILL.md"
    note = NOTE.format(code=edition_code(skill_dir), name=skill_dir.name)
    body = absolute_links(skill_body(skill_dir), main, skill_dir)
    return "\n".join([generated_header(skill_dir, Path("SKILL.md")), "", note, body, ""])


def anchor_for(rel: str) -> str:
    return "included-" + re.sub(r"[^a-z0-9]+", "-", rel.lower()).strip("-")


def route_url(name: str) -> str:
    return link_url(Path("route") / f"{name}.md")


def render_route(name: str, skill: str, files: tuple[str, ...]) -> str:
    """One page holding SKILL.md and every file the request needs, linked to each other by anchors."""
    skill_dir = SKILLS / skill
    included = {(skill_dir / rel).resolve(): anchor_for(rel) for rel in files}
    listed = ", ".join(f"`{rel}`" for rel in files)
    note = ROUTE_NOTE.format(code=edition_code(skill_dir), listed=listed, name=name)
    sections = []
    for rel in files:
        path = skill_dir / rel
        text = path.read_text(encoding="utf-8")
        if path.suffix == ".md":
            body = absolute_links(text, path, skill_dir, included)
        else:
            body = f"Copy this file as the starting point.\n\n```{path.suffix.lstrip('.')}\n{text.rstrip()}\n```"
        sections += [f'<a id="{included[path.resolve()]}"></a>', f"## Included: {rel}", "", body, ""]
    return "\n".join([
        generated_header(skill_dir, Path("SKILL.md"), *(Path(rel) for rel in files)),
        "",
        note,
        absolute_links(skill_body(skill_dir), skill_dir / "SKILL.md", skill_dir, included),
        "",
        *sections,
    ])


def render_index() -> str:
    rows = [f"| {request} | [{name}]({route_url(name)}) |" for name, request, _, _ in ROUTES]
    fallbacks = ", ".join(f"[{name}]({link_url(Path(f'{name}.md'))})" for name in bz.skill_names(SKILLS))
    return "\n".join([
        f"{GENERATED}. Do not edit. -->",
        "",
        "# Econ Agent Skills",
        "",
        INDEX_NOTE.format(fallbacks=fallbacks),
        "| The user wants to… | Open |",
        "| --- | --- |",
        *rows,
        "",
    ])


def render_router() -> str:
    rows = "\n".join(f"- {request}: {route_url(name)}" for name, request, _, _ in ROUTES)
    return ROUTER.format(rows=rows)


def readme_with_router(text: str) -> str:
    if not ROUTER_BLOCK.search(text):
        raise ValueError("README.md has no <!-- link-router --> block")
    block = f"```text\n{render_router()}\n```\n"
    return ROUTER_BLOCK.sub(lambda m: f"{m.group(1)}{block}{m.group(2)}", text)


def generated_pages() -> dict[Path, str]:
    pages = {}
    for name in bz.skill_names(SKILLS):
        skill_dir = SKILLS / name
        pages[OUT / f"{name}.md"] = render(skill_dir)
        for path in bz.included_files(skill_dir):
            rel = path.relative_to(skill_dir)
            if rel.suffix == ".md" and rel != Path("SKILL.md"):
                pages[OUT / link_path(name, rel)] = render_reference(skill_dir, rel)
    for name, _, skill, files in ROUTES:
        pages[OUT / "route" / f"{name}.md"] = render_route(name, skill, files)
    for old, name in MOVED.items():
        pages[OUT / old] = MOVED_PAGE.format(url=route_url(name), base=RAW_BASE)
    pages[OUT / f"{INDEX_NAME}.md"] = render_index()
    pages.update({
        OUT / f"{old}.md": REDIRECT.format(old=old, new=new, base=RAW_BASE)
        for old, new in RENAMED.items()
    })
    return pages


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="do not write; fail if link/ is out of date")
    args = parser.parse_args(argv)

    stale = False
    pages = generated_pages()
    for target, wanted in pages.items():
        relative = target.relative_to(ROOT)
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == wanted:
            print(f"OK: {relative} is up to date")
        elif args.check:
            stale = True
            print(f"ERROR: {relative} is out of date; run python3 tools/build_link_editions.py")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(wanted, encoding="utf-8")
            print(f"WROTE: {relative}")
    readme = README.read_text(encoding="utf-8")
    wanted_readme = readme_with_router(readme)
    if readme == wanted_readme:
        print("OK: README.md router is up to date")
    elif args.check:
        stale = True
        print("ERROR: README.md router is out of date; run python3 tools/build_link_editions.py")
    else:
        README.write_text(wanted_readme, encoding="utf-8")
        print("WROTE: README.md router")
    for target in sorted(set(OUT.rglob("*.md")) - pages.keys()):
        if target.read_text(encoding="utf-8").startswith(GENERATED):
            relative = target.relative_to(ROOT)
            if args.check:
                stale = True
                print(f"ERROR: {relative} is no longer generated; run python3 tools/build_link_editions.py")
            else:
                target.unlink()
                print(f"REMOVED: {relative}")
    return int(stale)


if __name__ == "__main__":
    sys.exit(main())
