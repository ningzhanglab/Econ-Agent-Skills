#!/usr/bin/env python3
"""Build the "link edition" of each skill, for trying a skill by pasting a link.

Usage:
  python tools/build_link_editions.py           # write link/<skill>.md
  python tools/build_link_editions.py --check   # fail if a file is out of date

An installed skill finds its reference files on disk. A chat agent that reads
SKILL.md from a URL has to build each reference address itself, and many chat
apps only open addresses that appear word for word in a page already read.
The link edition is SKILL.md with every relative link written as a full
address, a short note on what to fetch, and an index of every file in the
skill. It is generated; edit the skill, not the link edition.

Each page carries a short edition code, a hash of every file in the skill.
The paste prompt asks the agent to start its answer with that code, so a
reader can tell whether the page was really opened. The code changes when
any file of the skill changes, so rebuild after every skill edit.

Standard library only. Read-only on skills/; writes only into link/.
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_skill_zips as bz  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SKILLS = ROOT / "skills"
OUT = ROOT / "link"
RAW_BASE = "https://raw.githubusercontent.com/ningzhanglab/Econ-Agent-Skills/main"

# [text](relative/path) or [text](relative/path#anchor); web links and
# same-page anchors are left alone.
LOCAL_LINK_RE = re.compile(r"\]\((?![a-z][a-z0-9+.-]*:|#)([^)#\s]+)(?:#([^)\s]*))?\)")

NOTE = """> **Edition code: `{code}`**
>
> **You are reading this skill from a link, not from an installed folder.** Most of its rules are in the reference files linked below; every link on this page is a full address you can open.
>
> 1. Before answering, open each reference file this page names for the request. A rule you have not read is a rule you cannot follow.
> 2. Links inside a reference file are relative to that file. Find the target in the [file index](#file-index) at the end of this page and open it by its full address.
> 3. If a file cannot be opened, say which one and do not guess its content.
> 4. Begin your first answer with the line `Skill edition: {code}`, and end it with one line listing the skill files you read.
"""


def edition_code(skill_dir: Path) -> str:
    """Six hex characters that change when any file of the skill changes."""
    digest = hashlib.sha256()
    for path in bz.included_files(skill_dir):
        digest.update(path.relative_to(skill_dir).as_posix().encode("utf-8"))
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()[:6]


def skill_url(skill: str, rel: str) -> str:
    return f"{RAW_BASE}/skills/{skill}/{rel}"


def render(skill_dir: Path) -> str:
    skill = skill_dir.name
    text = (skill_dir / "SKILL.md").read_text(encoding="utf-8")
    parts = text.split("---\n", 2)
    if not text.startswith("---\n") or len(parts) < 3:
        raise ValueError(f"{skill_dir}/SKILL.md has no YAML frontmatter")
    frontmatter, body = parts[1], parts[2]

    def absolute(match: re.Match) -> str:
        rel, anchor = match.group(1), match.group(2)
        if not (skill_dir / rel).is_file():
            raise ValueError(f"{skill_dir}/SKILL.md links to a missing file: {rel}")
        link = f"]({skill_url(skill, rel)})"
        return f'{link} (section "{anchor}")' if anchor else link

    body = LOCAL_LINK_RE.sub(absolute, body).strip("\n")
    index = [
        f"- `{path.relative_to(skill_dir).as_posix()}`: {skill_url(skill, path.relative_to(skill_dir).as_posix())}"
        for path in bz.included_files(skill_dir)
        if path.name != "SKILL.md" or path.parent != skill_dir
    ]
    return "\n".join([
        f"<!-- Generated by tools/build_link_editions.py from skills/{skill}/SKILL.md. Do not edit. -->",
        "",
        NOTE.format(code=edition_code(skill_dir)),
        "```yaml",
        frontmatter.strip("\n"),
        "```",
        "",
        body,
        "",
        "## File index",
        "",
        f"Every file of this skill, with its full address. Folder: {RAW_BASE}/skills/{skill}/",
        "",
        *index,
        "",
    ])


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="do not write; fail if link/ is out of date")
    args = parser.parse_args(argv)

    stale = []
    for name in bz.skill_names(SKILLS):
        target = OUT / f"{name}.md"
        wanted = render(SKILLS / name)
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == wanted:
            print(f"OK: {target.relative_to(ROOT)} is up to date")
        elif args.check:
            stale.append(name)
            print(f"ERROR: {target.relative_to(ROOT)} is out of date; run python tools/build_link_editions.py")
        else:
            OUT.mkdir(exist_ok=True)
            target.write_text(wanted, encoding="utf-8")
            print(f"WROTE: {target.relative_to(ROOT)}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
